-- migration_055.sql（v1.1.2：历史「减免」单据方式文案订正）
-- 背景（负责人 2026-09-20 指令）：减免口径已由 CHG-v1.1.2-40 修订为「直接调减账单应收」，
--       但历史记录仍保留旧文案（「冲减当期账单」「自动抵扣下期」）——那是「减免当退款用」时代的措辞，
--       与现行账目不符（减免期间实缴被冲减、应收未动），页面「方式」列展示会误导。
-- 处置（CHG-v1.1.2-42）：
--   1) 账目已按新口径回填、或无需人工复核的减免记录 → 方式订正为「直接调减账单应收」；
--   2) 未回填者（migration_053 标记「历史减免超出未收余额…待复核」，或账单已删除未回填）
--      → 方式订正为「历史减免（旧口径）」，如实标注其按旧口径记账，避免文案与账目背离。
-- 幂等：只处理 refund_type = 1 且方式 != '直接调减账单应收' 的记录，重复执行不改变已订正结果。
-- 版本：055（2026-09-20）
-- ============================================================

UPDATE t_payment_refund
SET method = CASE
        WHEN EXISTS (
                SELECT 1 FROM t_bill b
                WHERE b.id = t_payment_refund.bill_id
                  AND (b.del_flag <> 0
                       OR EXISTS (SELECT 1 FROM t_bill_status_log l
                                  WHERE l.bill_id = b.id
                                    AND l.reason LIKE '历史减免超出未收余额（CHG-v1.1.2-40）%')))
            THEN '历史减免（旧口径）'
        ELSE '直接调减账单应收'
    END
WHERE refund_type = 1
  AND (method IS NULL OR method <> '直接调减账单应收');
