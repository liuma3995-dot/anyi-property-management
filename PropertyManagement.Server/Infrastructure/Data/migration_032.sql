-- ============================================================
-- migration_032.sql（M8 D8-0 品牌更名：演示小区名「澜庭小区」→「安怡小区」）
-- 背景：D8-0 更名范围＝产品对外文案；seed.sql 已把**全新库**的默认小区名
--       更新为「安怡小区」。本迁移负责把**存量库**（演示库 / 隔离测试库 / 已安装
--       环境）中的旧小区名同步为新名，避免「新装 = 安怡小区 / 存量 = 澜庭小区」
--       的数据基线漂移（报表、小区下拉等可见）。
-- 幂等：仅当存在旧名且不存在新名时才更新；重复执行影响 0 行。
-- 安全：不改表结构、不改 id、不触碰其它业务数据。
-- ============================================================

UPDATE t_community
   SET name = '安怡小区',
       updated_at = datetime('now','localtime')
 WHERE name = '澜庭小区'
   AND (SELECT COUNT(1) FROM t_community WHERE name = '安怡小区') = 0;
